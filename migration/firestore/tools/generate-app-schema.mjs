#!/usr/bin/env node
/**
 * Source schema for the Firestore application layer.
 *
 * Two outputs, both derived and never hand-edited:
 *
 *   migration/firestore/config/source-schema.json   committed snapshot of the live catalog:
 *                                                    columns, keys, defaults, CHECK constraints,
 *                                                    triggers and function signatures
 *   src/data/firestore/sourceSchema.generated.ts     the facts the document codec needs at runtime
 *
 * The first step reads migration/full-vertical.local/source-catalog.json, which the read-only
 * catalog export produces from the production snapshot. When that local file is absent the
 * committed snapshot is used, so the TypeScript output is reproducible without source access.
 *
 * Field naming reproduces migration/firestore/tools/full-migration-rehearsal.mjs exactly (see
 * ../lib/source-schema.mjs). A default or type this generator does not understand fails the run; an
 * unrecognised CHECK constraint is kept verbatim in `unparsedChecks` for explicit classification.
 *
 * Read-only against production. No network.
 */
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { buildSchema } from '../lib/source-schema.mjs';

const LOCAL_CATALOG = 'migration/full-vertical.local/source-catalog.json';
const SNAPSHOT = 'migration/firestore/config/source-schema.json';
const OUTPUT = 'src/data/firestore/sourceSchema.generated.ts';

const sha256 = (text) => createHash('sha256').update(text).digest('hex');
const fail = (code, detail) => { throw new Error(`${code}: ${detail}`); };
/** A BEFORE UPDATE trigger function whose only statement sets updated_at to the current time. */
const TOUCH_ONLY = /^CREATE OR REPLACE FUNCTION [^\n]+\n RETURNS trigger\n LANGUAGE plpgsql\n(?: [^\n]+\n)*AS \$function\$\s*BEGIN\s*NEW\.updated_at\s*=\s*(?:now\(\)|NOW\(\)|timezone\('utc'::text,\s*now\(\)\)|CURRENT_TIMESTAMP);\s*RETURN NEW;\s*END;?\s*\$function\$\s*$/i;

function snapshotFromCatalog(catalog) {
  const tables = {};
  const functionsByName = new Map();
  for (const fn of catalog.functions) {
    if (!functionsByName.has(fn.name)) functionsByName.set(fn.name, []);
    functionsByName.get(fn.name).push(fn);
  }
  for (const [name, table] of Object.entries(catalog.tables).sort(([a], [b]) => a.localeCompare(b))) {
    tables[name] = {
      triggers: table.triggers.map((trigger) => {
        const bodies = (functionsByName.get(trigger.function_name) ?? []).map((fn) => fn.definition ?? '');
        const touchOnly = /BEFORE UPDATE/.test(trigger.definition) && !/AFTER/.test(trigger.definition)
          && bodies.length === 1 && TOUCH_ONLY.test(bodies[0].replace(/\r\n/g, '\n'));
        return { name: trigger.tgname, definition: trigger.definition, function: trigger.function_name,
          functionSha256: bodies.length === 1 ? sha256(bodies[0]) : null,
          classification: touchOnly ? 'TOUCH_UPDATED_AT' : 'REQUIRES_VERTICAL_CLASSIFICATION' };
      }),
      columns: table.columns.map((column) => ({
        name: column.column_name, dataType: column.data_type, udt: column.udt_name,
        nullable: column.is_nullable !== 'NO', default: column.column_default ?? null,
        precision: column.numeric_precision, scale: column.numeric_scale,
      })),
      constraints: table.constraints.map((constraint) => ({ type: constraint.contype, definition: constraint.definition }))
        .sort((a, b) => `${a.type}${a.definition}`.localeCompare(`${b.type}${b.definition}`)),
    };
  }
  const functions = catalog.functions.map((fn) => ({ name: fn.name, args: fn.args, result: fn.result,
    securityDefiner: fn.security_definer, language: fn.language,
    definitionSha256: fn.definition ? sha256(fn.definition) : null }));
  return { generatedFrom: 'read-only production catalog (REPEATABLE READ READ ONLY snapshot)',
    catalogGeneratedAt: catalog.generatedAt, source: catalog.source, tables, functions };
}

let snapshot;
if (existsSync(LOCAL_CATALOG)) {
  snapshot = snapshotFromCatalog(JSON.parse(readFileSync(LOCAL_CATALOG, 'utf8')));
  if (!snapshot.source?.readOnly || snapshot.source?.rejectedWriteSqlState !== '25006') fail('CATALOG_NOT_READ_ONLY_PROVEN', LOCAL_CATALOG);
  writeFileSync(SNAPSHOT, `${JSON.stringify(snapshot, null, 2)}\n`);
} else {
  snapshot = JSON.parse(readFileSync(SNAPSHOT, 'utf8'));
}

const schema = buildSchema(snapshot);
// One line per column keeps the output reviewable in a diff without the weight of full indentation.
const renderTable = (spec) => {
  const { columns, ...rest } = spec;
  const head = JSON.stringify(rest).slice(1, -1);
  return `  ${JSON.stringify(spec.name)}: {${head},\n    "columns": [\n${columns.map((c) => `      ${JSON.stringify(c)}`).join(',\n')}\n    ]}`;
};
const body = [
  '// GENERATED by migration/firestore/tools/generate-app-schema.mjs from the read-only production catalog.',
  '// Do not edit by hand. Regenerate after any source schema change.',
  "import type { SourceSchema } from './sourceSchemaTypes';",
  '',
  'export const SOURCE_SCHEMA: SourceSchema = {',
  Object.values(schema).map(renderTable).join(',\n'),
  '};',
  '',
].join('\n');
writeFileSync(OUTPUT, body);
const unparsed = Object.values(schema).flatMap((table) => table.unparsedChecks.map((check) => `${table.name}: ${check}`));
console.log(JSON.stringify({ tables: Object.keys(schema).length,
  columns: Object.values(schema).reduce((n, t) => n + t.columns.length, 0),
  triggers: Object.values(schema).flatMap((t) => t.triggers.map((x) => `${t.name}.${x.name}:${x.classification}`)),
  sequenceDefaults: Object.values(schema).flatMap((t) => t.columns.filter((c) => c.default?.kind === 'sequence').map((c) => `${t.name}.${c.name}`)),
  unparsedChecks: unparsed.length, output: OUTPUT, snapshot: SNAPSHOT }, null, 2));
if (process.argv.includes('--show-unparsed')) for (const line of unparsed) console.log(line);

#!/usr/bin/env node
/**
 * Generate the source-coverage section of FIRESTORE_DATA_MODEL.md.
 *
 * The prose in that document is written by hand; the mapping table is generated
 * from the live inventory and the table map so it cannot drift out of date or
 * quietly omit a table. If the source grows a table with no decision, this
 * fails rather than producing a document that looks complete.
 *
 *   node migration/firestore/tools/generate-data-model-doc.mjs
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { TABLE_MAP, TABLE_MAP_BY_NAME, validateTableMap } from '../lib/table-map.mjs';
import { ENTITIES } from '../lib/entities.mjs';

const DOC = 'migration/firestore/FIRESTORE_DATA_MODEL.md';
const BEGIN = '<!-- BEGIN GENERATED SOURCE COVERAGE -->';
const END = '<!-- END GENERATED SOURCE COVERAGE -->';

const inventory = JSON.parse(
  readFileSync('migration/reports/firestore-source-domain-inventory.json', 'utf8'));

const validation = validateTableMap(inventory.tables.map((t) => t.name));
if (!validation.ok) {
  console.error(JSON.stringify(validation, null, 2));
  throw new Error('TABLE_MAP_INCOMPLETE');
}

const byName = new Map(inventory.tables.map((t) => [t.name, t]));
const escape = (text) => String(text).replace(/\|/g, '\\|');

const rows = TABLE_MAP.map((entry) => {
  const table = byName.get(entry.name);
  const entity = ENTITIES[entry.name];
  const decimals = table.columns.filter((c) => c.type === 'numeric').length;
  const json = table.columns.filter((c) => ['json', 'jsonb'].includes(c.type)).length;
  return {
    ...entry,
    columns: table.columns.length,
    primaryKey: table.primaryKey.join(', ') || '(none)',
    foreignKeys: table.foreignKeys.length,
    policies: table.policies.length,
    decimals,
    json,
    documentId: entity ? (entity.docId.toString().includes('bigintDocId')
      ? 'source BIGINT id, zero-padded'
      : entity.sourcePrimaryKey.join(' + '))
      : `source ${table.primaryKey.join(', ') || 'primary key'}`,
  };
});

const byDomain = rows.reduce((acc, row) => {
  (acc[row.domain] ??= []).push(row);
  return acc;
}, {});

const DOMAIN_TITLES = {
  identity: 'Identity and tenancy',
  travel: 'Travel (the active product)',
  restaurant: 'Restaurant vertical (legacy)',
  retail_auto: 'Retail and automotive vertical (legacy)',
  fiscal: 'Fiscal and regulatory (legacy)',
  whatsapp: 'WhatsApp automation (quarantined)',
};

let out = `${BEGIN}\n\n`;
out += '_This section is generated by `migration/firestore/tools/generate-data-model-doc.mjs`'
  + ' from the live source inventory and `lib/table-map.mjs`. Do not edit it by hand._\n\n';
out += `Source tables in the live schema: **${validation.liveTables}**. `
  + `Tables with a mapping decision: **${validation.mappedTables}**. `
  + `Unmapped: **${validation.unmapped.length}**. Unknown: **${validation.unknown}**.\n\n`;

for (const [domain, entries] of Object.entries(byDomain)) {
  out += `### ${DOMAIN_TITLES[domain] ?? domain} (${entries.length} tables)\n\n`;
  out += '| Source table | Disposition | Target path | Document id | Security field'
    + ' | Milestone | Cols | FKs | Num | JSON | Policies |\n';
  out += '|---|---|---|---|---|---|---|---|---|---|---|\n';
  for (const row of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    out += `| \`${row.name}\` | ${row.disposition} | \`${escape(row.target)}\` `
      + `| ${escape(row.documentId)} | \`${row.securityField ?? '—'}\` | ${row.milestone} `
      + `| ${row.columns} | ${row.foreignKeys} | ${row.decimals} | ${row.json} `
      + `| ${row.policies} |\n`;
  }
  out += '\n';
  const noted = entries.filter((e) => e.sourceQuirk || e.quarantined || e.hashChained);
  if (noted.length) {
    out += '**Notes**\n\n';
    for (const row of noted) {
      const flags = [
        row.sourceQuirk ? `source quirk: ${row.sourceQuirk}` : null,
        row.quarantined ? 'quarantined: migrated as history only, no automation re-enabled' : null,
        row.hashChained ? 'hash-chained: the chain must be re-verified after migration' : null,
      ].filter(Boolean);
      out += `- \`${row.name}\` — ${flags.join('; ')}\n`;
    }
    out += '\n';
  }
}

out += '### Milestone-1 entity contracts\n\n';
out += 'These are the tables migrated and reconciled in this milestone. Each row states the'
  + ' declared references the orphan checker enforces, and the ordering contract for'
  + ' append-only history.\n\n';
out += '| Target collection | References checked | Append-only | Ordering |\n|---|---|---|---|\n';
for (const [table, entity] of Object.entries(ENTITIES)) {
  const references = entity.references.length
    ? entity.references.map((r) => `\`${r.field}\` → \`${r.collection}\`${r.required ? ' (required)' : ''}`).join('<br>')
    : '—';
  const ordering = entity.ordering
    ? `by \`${entity.ordering.sequenceField}\` within \`${entity.ordering.parentField}\``
    : '—';
  out += `| \`${entity.collection}\` | ${references} | ${entity.appendOnly ? 'yes' : 'no'}`
    + ` | ${ordering} |\n`;
}

out += `\n### Decimal domains\n\n`;
const scales = {};
for (const d of inventory.decimalDomains) {
  const key = d.precision === null ? 'unconstrained NUMERIC' : `NUMERIC(${d.precision},${d.scale})`;
  scales[key] = (scales[key] ?? 0) + 1;
}
out += 'Every migrated decimal declares its scale. The scale is taken from the VALUE, not the'
  + ' column, because the source holds the same column at different scales.\n\n';
out += '| Source declaration | Columns |\n|---|---|\n';
for (const [key, count] of Object.entries(scales).sort((a, b) => b[1] - a[1])) {
  out += `| ${key} | ${count} |\n`;
}
out += `\nFloating-point columns in the source: **${inventory.floatDomains.length}**`
  + ` (${inventory.floatDomains.map((f) => `\`${f.table}.${f.column}\``).join(', ') || 'none'}).`
  + ' None of them is money — they are restaurant floor-plan geometry.\n';

out += `\n_Generated ${new Date().toISOString()} from a source inventory taken at`
  + ` ${inventory.generatedAt}._\n\n${END}`;

const existing = readFileSync(DOC, 'utf8');
const start = existing.indexOf(BEGIN);
const finish = existing.indexOf(END);
if (start === -1 || finish === -1) throw new Error('DOC_MARKERS_MISSING');
writeFileSync(DOC, existing.slice(0, start) + out + existing.slice(finish + END.length));

console.log(JSON.stringify({
  status: 'GENERATED', document: DOC,
  liveTables: validation.liveTables, mapped: validation.mappedTables,
  unmapped: validation.unmapped.length, unknown: validation.unknown,
  milestone1Entities: Object.keys(ENTITIES).length,
}, null, 2));

#!/usr/bin/env node
/**
 * Build the synthetic-residue manifest entirely offline.
 *
 * The Firestore daily quota is exhausted, so this touches nothing but local files: the run
 * manifests each smoke wrote before creating anything, the sweep records saying what was already
 * removed, and the copy journal that defines the 1,474-document migration baseline.
 *
 * Three kinds of path come out of that:
 *
 *   DETERMINISTIC   users/{uid}, businessOwners/{uid}, businesses/{businessId} — the tenant
 *                   bootstrap writes exactly these, so they can be named without asking Firestore
 *   DERIVABLE       businesses/{businessId} for a run whose manifest never recorded the id; one
 *                   read of businessOwners/{uid} after reset yields it
 *   ENUMERABLE      vertical documents under a known business, whose ids were generated by the
 *                   repositories and recorded nowhere; these need listing, but only of
 *                   subcollections of our own six business documents, never a global scan
 *
 * Naming that third class honestly matters. A manifest that claimed to be exhaustive when it is not
 * would license a broader cleanup later on the grounds that "the manifest said so".
 *
 *   node migration/firestore/tools/prepare-residue-manifest.mjs
 */
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { sha256 } from '../lib/production-guard.mjs';

const LOCAL = 'migration/post-cutover-smoke.local';
const JOURNAL = 'migration/production-copy.local/bulkcopy-15363817-711a-4b52-9414-4885a8585bf4.json';
const LEDGER = 'migration/firestore/config/production-auth-ledger-plan.json';
const OUT = 'migration/post-cutover-smoke.local/residue-manifest.json';
const REPORT = 'migration/reports/synthetic-residue-manifest.json';
const RECONCILIATION = 'migration/reports/firestore-production-reconciliation.json';

const files = readdirSync(LOCAL).filter((name) => name.endsWith('.json'));
const runs = new Map();
for (const name of files) {
  if (name === 'residue-manifest.json') continue;
  const body = JSON.parse(readFileSync(join(LOCAL, name), 'utf8'));
  if (name.endsWith('.sweep.json')) {
    const runId = body.runId ?? name.replace('.json.sweep.json', '');
    const entry = runs.get(runId) ?? {};
    entry.sweep = body;
    runs.set(runId, entry);
  } else {
    const entry = runs.get(body.runId) ?? {};
    entry.manifest = body;
    runs.set(body.runId, entry);
  }
}

/**
 * A reconciliation that reported zero unexpected documents is proof that everything finishing before
 * it was cleaned, whatever its own bookkeeping says. Using it as a watermark keeps runs that cleaned
 * themselves out of the residue set instead of scheduling 101 deletes for documents that are gone.
 *
 * Runs after the watermark are residue-bearing unless their own sweep recorded residue zero.
 */
const reconciliation = JSON.parse(readFileSync(RECONCILIATION, 'utf8'));
const cleanWatermark = reconciliation.coverage?.unexpectedDocuments === 0
  ? Date.parse(reconciliation.generatedAt) : 0;
const runTime = (entry) => Date.parse(entry.manifest.createdAt ?? 0) || 0;

const unswept = [...runs.entries()]
  .filter(([, entry]) => {
    if (!entry.manifest) return false;
    if (entry.sweep && (entry.sweep.residue ?? 1) === 0) return false;
    return runTime(entry) > cleanWatermark;
  })
  .map(([runId, entry]) => ({ runId, manifest: entry.manifest, sweep: entry.sweep ?? null }));

const migrated = new Set(JSON.parse(readFileSync(JOURNAL, 'utf8')).writtenPaths);
const ledger = JSON.parse(readFileSync(LEDGER, 'utf8'));
const migratedFingerprints = new Set(ledger.users.map((user) => user.sourceUidFingerprint));
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

const deterministic = [];
const derivable = [];
const enumerable = [];
const identities = { uids: new Set(), businessIds: new Set() };

for (const run of unswept) {
  const already = new Set(run.sweep?.swept ?? []);
  for (const uid of run.manifest.authUids ?? []) {
    identities.uids.add(uid);
    for (const path of [`users/${uid}`, `businessOwners/${uid}`]) {
      if (!already.has(path)) deterministic.push({ path, runId: run.runId, kind: 'tenant-bootstrap' });
    }
  }
  const businessIds = run.manifest.businessIds ?? [];
  if (businessIds.length) {
    for (const businessId of businessIds) {
      identities.businessIds.add(businessId);
      const path = `businesses/${businessId}`;
      if (!already.has(path)) deterministic.push({ path, runId: run.runId, kind: 'tenant-bootstrap' });
      enumerable.push({ parent: path, runId: run.runId,
        method: 'listCollections on this document, then listDocuments per subcollection' });
    }
  } else {
    // The run crashed before it recorded its business ids; businessOwners/{uid}.businessId has them.
    for (const uid of run.manifest.authUids ?? []) {
      derivable.push({ resolveFrom: `businessOwners/${uid}`, field: 'businessId',
        yields: 'businesses/{businessId} plus its subcollections', runId: run.runId });
    }
  }
  // Paths the run itself recorded, when it had any (the earlier hand-authored smoke did).
  for (const path of run.manifest.firestorePaths ?? []) {
    if (!already.has(path)) deterministic.push({ path, runId: run.runId, kind: 'recorded-by-run' });
  }
}

const paths = [...new Set(deterministic.map((entry) => entry.path))].sort();

// ---- proofs ---------------------------------------------------------------------------------------
const overlapsBaseline = paths.filter((path) => migrated.has(path));
const uidsAreSynthetic = [...identities.uids].every((uid) => !UUID.test(uid));
const uidFingerprints = [...identities.uids]
  .map((uid) => sha256(uid).slice(0, 12));
const touchesMigratedIdentity = uidFingerprints.filter((fp) => migratedFingerprints.has(fp));
// A customer path is one of the migrated 1,474 or one owned by a migrated business. The business
// ids here were generated by the synthetic runs, so none can be a customer business, but the check
// is made rather than argued.
const migratedBusinessIds = new Set([...migrated]
  .filter((path) => path.startsWith('businesses/'))
  .map((path) => path.split('/')[1]));
const touchesCustomerBusiness = [...identities.businessIds]
  .filter((id) => migratedBusinessIds.has(id));

const manifest = {
  generatedAt: new Date().toISOString(),
  mode: 'OFFLINE_NO_FIRESTORE_CONTACT',
  reason: 'SYNTHETIC_SMOKE_RESIDUE',
  cleanWatermark: { reconciliationAt: reconciliation.generatedAt,
    unexpectedDocumentsThen: reconciliation.coverage?.unexpectedDocuments ?? null,
    meaning: 'runs that finished before this are proven clean by it' },
  unsweptRuns: unswept.map((run) => ({ runId: run.runId,
    authUids: (run.manifest.authUids ?? []).length,
    businessIds: (run.manifest.businessIds ?? []).length,
    sweepOutcome: run.sweep ? `residue=${run.sweep.residue}` : 'NO_SWEEP_RECORDED' })),
  syntheticUids: [...identities.uids].sort(),
  syntheticBusinessIds: [...identities.businessIds].sort(),
  deterministicPaths: paths,
  derivable,
  enumerable,
  expectedDeterministicCount: paths.length,
  proofs: {
    overlapsMigrationBaseline: overlapsBaseline.length,
    allUidsAreNonUuidSynthetic: uidsAreSynthetic,
    touchesMigratedIdentity: touchesMigratedIdentity.length,
    touchesCustomerBusiness: touchesCustomerBusiness.length,
    migrationBaselineSize: migrated.size,
  },
  note: 'deterministicPaths is exact. enumerable and derivable are NOT paths yet: the repositories '
    + 'generated those document ids and recorded them nowhere, so they must be listed after reset, '
    + 'and only by listing subcollections of these six business documents.',
};
manifest.integrityHash = sha256(JSON.stringify(manifest, Object.keys(manifest).sort()));

const blocked = overlapsBaseline.length > 0 || !uidsAreSynthetic
  || touchesMigratedIdentity.length > 0 || touchesCustomerBusiness.length > 0;

mkdirSync(LOCAL, { recursive: true });
writeFileSync(OUT, `${JSON.stringify(manifest, null, 2)}\n`, { mode: 0o600 });
writeFileSync(REPORT, `${JSON.stringify({ ...manifest, deterministicPaths: paths.length,
  decision: blocked ? 'BLOCKED' : 'SAFE_TO_DELETE_AFTER_RESET' }, null, 2)}\n`);

console.log(JSON.stringify({
  decision: blocked ? 'BLOCKED' : 'SAFE_TO_DELETE_AFTER_RESET',
  cleanWatermark: manifest.cleanWatermark,
  unsweptRuns: manifest.unsweptRuns,
  syntheticUids: manifest.syntheticUids.length,
  syntheticBusinessIds: manifest.syntheticBusinessIds.length,
  expectedDeterministicResidue: paths.length,
  derivableBusinessLookups: derivable.length,
  enumerableParents: enumerable.length,
  proofs: manifest.proofs,
  manifest: OUT,
  manifestHash: manifest.integrityHash,
  firestoreOperationsUsed: 0,
}, null, 2));
process.exitCode = blocked ? 1 : 0;
